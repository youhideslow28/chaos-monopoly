/**
 * Retrieve a card by its ID or legacy alias
 */
export function getChaosCardById(cardId: string): ChaosCard | undefined {
  const actualId = LEGACY_CARD_ALIASES[cardId] || cardId;
  return CHAOS_CARDS.find(c => c.id === actualId || c.id === cardId);
}

/**
 * Retrieve all cards belonging to a specific category
 */
export function getChaosCardsByCategory(category: ChaosCategory): ChaosCard[] {
  return CHAOS_CARDS.filter(c => c.category === category);
}

/**
 * Retrieve all cards of a given rarity tier
 */
export function getChaosCardsByRarity(rarity: ChaosRarity): ChaosCard[] {
  return CHAOS_CARDS.filter(c => c.rarity === rarity);
}
